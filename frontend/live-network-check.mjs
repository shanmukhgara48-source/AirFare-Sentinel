// Read-only checks of a live deployment. Never clears data or triggers provider calls.
import assert from 'node:assert/strict'
import { chromium } from 'playwright'
const base=process.env.FAREPULSE_BASE_URL ?? 'http://127.0.0.1:5179'
const browser=await chromium.launch()
try{
 const context=await browser.newContext({viewport:{width:1440,height:1000}})
 const page=await context.newPage();const errors=[]
 page.on('pageerror',error=>errors.push(error.message))
 const get=async path=>{const r=await context.request.get(base+path);assert.ok(r.ok(),`${path}: HTTP ${r.status()}`);return r.json()}
 const version=await get('/api/version');const provider=await get('/api/provider/status');const source=await get('/api/admin/analysis-source');const network=await get('/api/network')
 assert.equal(version.demo_mode,false);assert.equal(version.live_only,true)
 assert.equal(provider.live_fetch_enabled,true);assert.equal(provider.active_live_provider,'ignav')
 assert.equal(source.active_analysis_source,'live');assert.deepEqual(source.available_analysis_sources,['live'])
 assert.ok(network.routes>14);assert.ok(network.quotes>1000)
 await page.goto(base+'/',{waitUntil:'networkidle'})
 await page.locator('.atlas-primary-fare strong').waitFor({timeout:30000})
 const shown=await page.locator('.atlas-route-hit').count()
 assert.ok(shown>14 && shown<=30,'Default map is capped at 30 major directions')
 assert.equal(await page.getByRole('button',{name:'Inspect DEL-HWR',exact:true}).count(),0,'Smaller route hidden by default')
 await page.getByRole('button',{name:'All routes',exact:true}).click()
 assert.equal(await page.locator('.atlas-route-hit').count(),network.routes,'Full network remains available')
 await page.getByLabel('Map route',{exact:true}).selectOption('DEL-HWR')
 assert.match(await page.locator('.atlas-route-title h3').textContent(),/DEL.*HWR/)
 await page.getByRole('button',{name:'Major routes',exact:true}).click()
 assert.equal(await page.locator('.atlas-route-hit').count(),shown)
 assert.doesNotMatch(await page.locator('.atlas-route-title h3').textContent(),/HWR/,'Selected evidence follows visible scope')
 assert.equal(await page.locator('.live-flight-row').count(),0,'Flight lists start collapsed')
 assert.equal(await page.locator('.overview-analysis-body').count(),0,'Analyst charts start collapsed')
 assert.equal(await page.getByLabel('Map airline',{exact:true}).isVisible(),false)
 await page.getByRole('button',{name:'Filters',exact:true}).click()
 assert.equal(await page.getByLabel('Map airline',{exact:true}).isVisible(),true)
 assert.deepEqual(await page.locator('optgroup[label="Leading Indian carriers"] option').allTextContents(),['IndiGo · 6E','Air India · AI','Air India Express · IX','Akasa Air · QP','SpiceJet · SG'])
 await page.getByRole('button',{name:'Hide filters',exact:true}).click()
 await page.locator('.overview-analysis > summary').click()
 await page.locator('.overview-filters').waitFor()
 assert.equal(await page.locator('[data-testid=publication-gate]').isVisible(),true)
 await page.locator('.overview-analysis > summary').click()
 await page.locator('.atlas-route-analysis > summary').click()
 assert.equal(await page.getByRole('heading',{name:'Fare trajectory',exact:true}).isVisible(),true)
 await page.locator('.atlas-route-analysis > summary').click()
 await page.evaluate(()=>scrollTo(0,0))
 await page.screenshot({path:'/tmp/airfare-simple-desktop.png',fullPage:true})
 await page.setViewportSize({width:390,height:844})
 await page.screenshot({path:'/tmp/airfare-simple-mobile.png',fullPage:true})
 await page.setViewportSize({width:1440,height:1000})
 assert.equal(await page.getByTestId('operating-mode').locator('strong').textContent(),'Live fare quote snapshots')
 assert.match(await page.locator('.atlas-source-strip').textContent(),/Live fare quote snapshots/)
 assert.ok(await page.locator('.atlas-route-hit').count()>14)
 const options=await page.getByLabel('Map route',{exact:true}).locator('option').allTextContents()
 const outside=options.find(route=>route==='BOM-AMD') ?? options.find(route=>route.includes('AMD'))
 assert.ok(outside,'An airport outside the original six appears on the map')
 await page.getByLabel('Map route',{exact:true}).selectOption(outside)
 await page.locator('.atlas-flight-disclosure > summary').click()
 await page.locator('.live-flight-row').first().waitFor()
 const flights=await get(`/api/live-itineraries?origin=${outside.split('-')[0]}&destination=${outside.split('-')[1]}&limit=10`)
 assert.equal(await page.locator('.live-flight-row').count(),flights.rows.length)
 const first=flights.rows[0]
 const displayed=await page.locator('.live-flight-row b').first().textContent()
 assert.equal(displayed.replace(/[^\d.]/g,''),first.total_fare.toFixed(2),'Exact returned amount including paise')
 assert.equal(await page.locator('.live-flight-row strong').first().textContent(),first.flight_number||first.airline)
 assert.ok(flights.rows.every(row=>row.source_type==='live'&&row.provider==='ignav'))
 await page.getByLabel('Map route',{exact:true}).selectOption('')
 await page.screenshot({path:'/tmp/airfare-live-desktop.png',fullPage:true})
 for(const width of [390,768,1280]){
  await page.setViewportSize({width,height:844})
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth-window.innerWidth)<=2,`No overflow at ${width}px`)
 }
 await page.setViewportSize({width:390,height:844})
 await page.screenshot({path:'/tmp/airfare-live-mobile.png',fullPage:true})
 for(const path of ['/trends','/spikes','/compare','/competition','/vulnerability','/fairness','/whatif','/method','/admin']){
  await page.goto(base+path,{waitUntil:'networkidle'})
  assert.match(await page.getByTestId('operating-mode').textContent(),/Live fare quote snapshots/)
  assert.equal(await page.getByRole('button',{name:'Load sample data',exact:true}).count(),0)
 }
 await page.getByRole('button',{name:'Fetch nationwide network',exact:true}).waitFor()
 assert.deepEqual(errors,[])
 assert.equal((await get('/api/network')).quotes,network.quotes,'Display selection did not remove observations')
 console.log('PASS: major route limit, full network toggle, leading airline names, collapsed details, expandable filters and preserved analytics, live-only gate, Ignav provenance, expanded route map, individual flight quotes, exact INR amounts, mobile layouts, all existing pages and no synthetic loading controls')
}finally{await browser.close()}
