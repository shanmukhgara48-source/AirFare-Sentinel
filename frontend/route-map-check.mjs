// Read-only browser contract checks against the isolated local preview.
import assert from 'node:assert/strict'
import { chromium } from 'playwright'
const base = process.env.FAREPULSE_BASE_URL ?? 'http://127.0.0.1:5179'
const browser = await chromium.launch()
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
  const page = await context.newPage()
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  const ready = async () => {
    await page.locator('.atlas-primary-fare strong').waitFor({timeout:30000})
    await page.waitForFunction(() => !document.querySelector('.atlas-mini-loading') && !document.querySelector('.atlas-quality')?.textContent.includes('Checking'), null, {timeout:30000})
  }
  await page.goto(`${base}/routes`, {waitUntil:'networkidle'}); await ready()
  assert.equal(await page.locator('.atlas-route-hit').count(),14)
  assert.match(await page.getByTestId('operating-mode').textContent(),/Demo Mode/)
  assert.match(await page.locator('.atlas-source-strip').textContent(),/Demo dataset/)
  const rows = (await (await context.request.get(`${base}/api/compare?dimension=route`)).json()).rows
  const delbom = rows.find(row=>row.group==='DEL-BOM')
  assert.equal((await page.locator('.atlas-primary-fare strong').textContent()).replace(/[^\d.]/g,''), delbom.avg_fare.toFixed(2))
  assert.equal(await page.locator('.atlas-spark svg').count(), 2)
  await page.screenshot({path:'/tmp/airfare-route-desktop.png',fullPage:true})
  const reverse = page.getByRole('button',{name:'Inspect BOM-DEL',exact:true})
  await reverse.focus(); await reverse.press('Enter')
  assert.match(await page.locator('.atlas-route-title h3').textContent(),/BOM.*DEL/)
  await page.getByRole('button',{name:'Focus',exact:true}).click()
  assert.equal(await page.locator('.atlas-route:not(.selected)').first().getAttribute('opacity'),'0.07')
  await page.getByRole('button',{name:'Cost',exact:true}).click()
  assert.match(await page.locator('.atlas-legend').textContent(),/₹7/)
  await page.getByRole('button',{name:'Risk',exact:true}).click()
  assert.match(await page.locator('.atlas-map-readout').textContent(),/100/)
  await page.getByRole('button',{name:'Table',exact:true}).click()
  assert.equal(await page.locator('.atlas-table tbody tr').count(),14)
  await page.locator('.atlas-table').getByRole('button',{name:'DEL → CCU',exact:true}).click()
  assert.match(await page.locator('.atlas-route-title h3').textContent(),/DEL.*CCU/)
  await page.getByLabel('Map route',{exact:true}).selectOption('BLR-HYD')
  assert.equal(await page.locator('.atlas-table tbody tr').count(),1)
  await page.getByLabel('Map route',{exact:true}).selectOption('')
  await page.getByRole('button',{name:'Map',exact:true}).click()
  await page.getByRole('button',{name:'Scan',exact:true}).click()
  const before = await page.locator('.atlas-route-title h3').textContent()
  await page.waitForTimeout(4700)
  assert.notEqual(await page.locator('.atlas-route-title h3').textContent(),before)
  await page.getByRole('button',{name:'Scan',exact:true}).click()
  await page.getByRole('button',{name:'Pause motion',exact:true}).click()
  assert.equal(await page.locator('.india-route-map').evaluate(svg=>svg.animationsPaused()),true)
  await page.getByRole('button',{name:'Resume motion',exact:true}).click()
  await page.emulateMedia({reducedMotion:'reduce'})
  await page.waitForTimeout(80)
  assert.equal(await page.getByRole('button',{name:'Scan',exact:true}).isDisabled(),true)
  assert.equal(await page.locator('.india-route-map').evaluate(svg=>svg.animationsPaused()),true)
  await page.emulateMedia({reducedMotion:'no-preference'})
  await page.getByRole('button',{name:'Filters',exact:true}).click()
  await page.getByLabel('Map airline',{exact:true}).selectOption('BW2'); await ready()
  assert.match(await page.locator('.route-intelligence').textContent(),/Backend route index/)
  await page.getByLabel('Map fare class',{exact:true}).selectOption('ECONOMY_SAVER'); await ready()
  await page.getByLabel('Map lead time',{exact:true}).selectOption('D00_03'); await ready()
  for(const width of [390,768,1280]){
    await page.setViewportSize({width,height:844})
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth-window.innerWidth)<=2,`No horizontal overflow at ${width}`)
    await page.getByRole('button',{name:'Table',exact:true}).click()
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth-window.innerWidth)<=2,`Table overflow contained at ${width}`)
    await page.getByRole('button',{name:'Map',exact:true}).click()
  }
  await page.setViewportSize({width:390,height:844})
  await page.goto(`${base}/routes`,{waitUntil:'networkidle'});await ready()
  await page.screenshot({path:'/tmp/airfare-route-mobile.png',fullPage:true})
  await page.getByRole('button',{name:'Filters',exact:true}).click()
  assert.equal(await page.getByLabel('Map analysis source',{exact:true}).isVisible(),true)
  // Emulate source states in the browser only; no stored rows or settings change.
  await page.setViewportSize({width:1440,height:1000})
  const sourceState=await (await context.request.get(`${base}/api/admin/analysis-source`)).json()
  const filterState=await (await context.request.get(`${base}/api/filters`)).json()
  for(const source of ['live','imported']){
    await page.route('**/api/admin/analysis-source',route=>route.fulfill({json:{...sourceState,active_analysis_source:source,available_analysis_sources:[source],dataset_mode:source}}))
    await page.route('**/api/filters',route=>route.fulfill({json:{...filterState,active_source_type:source,source_types:[source]}}))
    await page.route('**/api/export/observations.csv?*',route=>route.fulfill({contentType:'text/csv',body:`source_type,provider,total_fare,quote_date\n${source},amadeus,12345,2026-09-01\n`}))
    await page.reload({waitUntil:'networkidle'});await ready()
    assert.match(await page.locator('.atlas-source-strip').textContent(),source==='live'?/Live fare quote snapshots/:/Imported observations/)
    if(source==='live')assert.match(await page.locator('.atlas-provider').textContent(),/Provider: amadeus/, 'Uses observed provider rather than configured Ignav')
    await page.unrouteAll({behavior:'wait'})
  }
  await page.route('**/api/compare?*',route=>route.fulfill({json:{empty:true,rows:[]}}))
  await page.reload({waitUntil:'networkidle'})
  await page.getByRole('heading',{name:'No matching observations'}).waitFor()
  assert.equal(await page.locator('.atlas-route-hit').count(),14)
  assert.equal(await page.locator('.atlas-primary-fare').count(),0)
  await page.unrouteAll({behavior:'wait'})
  await page.route('**/api/competition',route=>route.abort())
  await page.reload({waitUntil:'networkidle'});await ready()
  assert.match(await page.locator('.atlas-partial').textContent(),/Competition context unavailable/)
  assert.equal(await page.locator('.atlas-primary-fare').count(),1)
  await page.unrouteAll({behavior:'wait'})
  assert.deepEqual(errors,[])
  console.log('PASS: route map, real fares, curves, keyboard selection, focus, views, filters, scan, reduced motion, responsive layouts, observed-provider provenance, live/imported/empty/partial-error states')
} finally {await browser.close()}
